"""Rewrite conformance/gaps.toml from the current native Mule results.

Run with `uv run python -m tools.record_conformance_gaps`. Each program is
compared with CPython; every program Mule rejects or runs differently is
recorded with its exact diagnostic or output, and passing programs are dropped.
"""

import argparse
import tempfile
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from test.conformance.cases import (
    GAPS,
    Gap,
    discover_programs,
    format_gap,
)


def observe(program):
    """Return the program's current gap, or None when Mule matches CPython."""
    with tempfile.TemporaryDirectory() as directory:
        directory = Path(directory)
        reference = program.run_reference(directory)
        failure = program.compile(directory / "program")
        if failure is not None:
            file = failure.file if failure.file != program.path.resolve() else None
            return Gap("compile", failure.message, file=file, line=failure.line)
        native = program.run([str(directory / "program")], directory)
        if native.matches(reference):
            return None
        last_error_line = native.stderr.strip().rpartition("\n")[2]
        reason = last_error_line or "native output differs from CPython"
        return Gap("run", reason, failure=native)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--jobs", type=int, default=6)
    jobs = parser.parse_args().jobs

    programs = discover_programs()
    with ProcessPoolExecutor(max_workers=jobs) as pool:
        gaps = list(pool.map(observe, programs))
    entries = [
        format_gap(program.id, gap)
        for program, gap in zip(programs, gaps, strict=True)
        if gap is not None
    ]
    header = "# Generated by tools/record_conformance_gaps.py; do not edit by hand.\n"
    GAPS.write_text(header + "\n" + "\n".join(entries), encoding="utf-8")
    print(f"{len(programs) - len(entries)} of {len(programs)} programs match CPython")
    print(f"recorded {len(entries)} gaps in {GAPS}")


if __name__ == "__main__":
    main()
