#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.14"
# dependencies = []
# ///
"""Generate stdlib/_ast.py from the running CPython's ``_ast`` node classes.

CPython builds ``_ast`` from ``Parser/Python.asdl``; the node hierarchy, field
names, location attributes and field types are read back from the classes the
running interpreter defines, so the generated module matches its grammar.
Optional fields default to None as class attributes and list fields to new
empty lists, following CPython 3.13 and later.
"""

import _ast
import argparse
import types
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[1] / "stdlib" / "_ast.py"
COMMAND = "uv run tools/generate_ast_module.py"


def ordered_classes():
    """Node classes with every base before its subclasses."""
    classes = [
        value
        for name, value in sorted(vars(_ast).items())
        if isinstance(value, type) and issubclass(value, _ast.AST)
    ]
    ordered, seen = [], set()

    def visit(cls):
        if cls in seen or cls is object:
            return
        for base in cls.__bases__:
            visit(base)
        seen.add(cls)
        ordered.append(cls)

    for cls in classes:
        visit(cls)
    return ordered


def field_kind(annotation):
    """'*' for a list field, '?' for an optional one, '' for a required one."""
    if isinstance(annotation, types.GenericAlias) and annotation.__origin__ is list:
        return "*"
    if isinstance(annotation, types.UnionType) and type(None) in annotation.__args__:
        return "?"
    return ""


def type_expression(annotation):
    if isinstance(annotation, types.GenericAlias) and annotation.__origin__ is list:
        return f"_Sequence({type_expression(annotation.__args__[0])})"
    if isinstance(annotation, types.UnionType):
        members = [arg for arg in annotation.__args__ if arg is not type(None)]
        return type_expression(members[0]) if len(members) == 1 else "object"
    if isinstance(annotation, type):
        return annotation.__name__ if annotation.__module__ == "ast" else annotation.__name__
    return "object"


def generate():
    lines = [
        f'"""Python syntax tree node classes, generated by `{COMMAND}`.',
        "",
        "This provides the interface of CPython's ``_ast`` extension module, whose",
        "classes CPython generates from ``Parser/Python.asdl``: the node hierarchy,",
        "each class's ``_fields`` and location ``_attributes``, and its field types.",
        '"""',
        "",
        "# ruff: noqa: E501",
        "",
    ]
    for name in sorted(vars(_ast)):
        value = getattr(_ast, name)
        if name.startswith("PyCF_"):
            lines.append(f"{name} = {value!r}")
    lines += [
        "",
        "",
        "class _Sequence:",
        '    """A list field\'s type, as ``list[element]`` reports it."""',
        "",
        "    __origin__ = list",
        "",
        "    def __init__(self, element):",
        "        self.__args__ = (element,)",
        "",
        "",
        "class AST:",
        '    """The base of every syntax tree node."""',
        "",
        "    _fields = ()",
        "    _attributes = ()",
        "    _field_kinds = ()",
        "    __match_args__ = ()",
        "",
        "    def __init__(self, *args, **keywords):",
        "        fields = self._fields",
        "        if len(args) > len(fields):",
        "            raise TypeError(",
        '                f"{type(self).__name__} constructor takes at most "',
        '                f"{len(fields)} positional argument{\'\' if len(fields) == 1 else \'s\'}"',
        "            )",
        "        for index in range(len(args)):",
        "            setattr(self, fields[index], args[index])",
        "        for name in keywords:",
        "            if name in fields[: len(args)]:",
        "                raise TypeError(",
        '                    f"{type(self).__name__} got multiple values for argument {name!r}"',
        "                )",
        "            setattr(self, name, keywords[name])",
        "        for index in range(len(args), len(fields)):",
        "            name = fields[index]",
        "            if name not in keywords and self._field_kinds[index] == '*':",
        "                setattr(self, name, [])",
        "",
        "    def __reduce__(self):",
        "        return type(self), (), self.__dict__",
        "",
        "    def __replace__(self, **keywords):",
        "        values = {}",
        "        for name in self._fields + self._attributes:",
        "            if hasattr(self, name):",
        "                values[name] = getattr(self, name)",
        "        values.update(keywords)",
        "        return type(self)(**values)",
        "",
    ]
    field_types = []
    for cls in ordered_classes():
        if cls is _ast.AST:
            continue
        bases = ", ".join(base.__name__ for base in cls.__bases__)
        lines += ["", f"class {cls.__name__}({bases}):"]
        fields = cls._fields
        annotations = getattr(cls, "_field_types", {})
        kinds = tuple(field_kind(annotations.get(name)) for name in fields)
        lines.append(f"    _fields = {fields!r}")
        lines.append(f"    _attributes = {cls._attributes!r}")
        lines.append(f"    _field_kinds = {kinds!r}")
        lines.append(f"    __match_args__ = {fields!r}")
        for name, kind in zip(fields, kinds, strict=True):
            if kind == "?":
                lines.append(f"    {name} = None")
        if annotations:
            entries = ", ".join(
                f"{name!r}: {type_expression(annotation)}"
                for name, annotation in annotations.items()
            )
            field_types.append(f"{cls.__name__}._field_types = {{{entries}}}")
        lines.append("")
    lines += ["", "AST._field_types = {}", *field_types, ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    output = parser.parse_args().output
    output.write_text(generate(), encoding="utf-8")


if __name__ == "__main__":
    main()
