def numeric(chr, default=_MISSING, /):
    cp = _character(chr)
    dig = digit_value(cp)
    if dig >= 0:
        return float(dig)
    low = 0
    high = len(_NUMERIC_RECORDS) // 4
    while low < high:
        middle = (low + high) // 2
        at = middle * 4
        code = _NUMERIC_RECORDS[at] | (_NUMERIC_RECORDS[at + 1] << 8) | (_NUMERIC_RECORDS[at + 2] << 16)
        if code == cp:
            return _NUMERIC_VALUES[_NUMERIC_RECORDS[at + 3]]
        if code < cp:
            low = middle + 1
        else:
            high = middle
    if default is _MISSING:
        raise ValueError("not a numeric character")
    return default


def name(chr, default=_MISSING, /):
    from _unicode_names import ALGORITHMIC_RANGES, _KEYS, _RECORDS, _VALUES, _u24

    cp = _character(chr)
    if cp < 0x20 or 0x7F <= cp <= 0x9F:
        if default is _MISSING:
            raise ValueError("no such name")
        return default
    override = _CANONICAL_OVERRIDES.get(cp)
    if override is not None:
        return override
    for prefix, ranges in ALGORITHMIC_RANGES.items():
        if prefix == b"TANGUT IDEOGRAPH-":
            continue
        for first, last in ranges:
            if first <= cp <= last:
                return prefix.decode("ascii") + format(cp, "X")
    at = 0
    limit = len(_RECORDS)
    while at < limit:
        if _RECORDS[at + 7] == 1:
            val_start = _u24(_RECORDS, at + 4)
            if _u24(_VALUES, val_start) == cp:
                key_start = _u24(_RECORDS, at)
                return _KEYS[key_start : key_start + _RECORDS[at + 3]].decode("ascii")
        at += 8
    if default is _MISSING:
        raise ValueError("no such name")
    return default


