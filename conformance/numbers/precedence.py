"""Operator precedence and associativity for arithmetic, unary, comparison, and boolean operators."""

x = 3
print("neg pow", -2**2, (-2)**2, -2**-2, 2**-1)
print("pow right assoc", 2**3**2, (2**3)**2, 2**2**0)
print("unary chains", - - x, - + - x, + - + x, ~-x, -~x, ~~x, bool(x), - - - x)
print("unary pow", -x**2, (-x)**2, ~x**2, 2**-x, 2** -x)
print("mul/div left assoc", 100 / 10 / 5, 100 // 7 * 7, 2 * 3 % 4, 2 * (3 % 4), 7 % 4 * 3)
print("add/sub left assoc", 10 - 4 - 3, 10 - (4 - 3), 1 + 2 * 3 - 4 / 2)
print("shift vs add", 1 << 2 + 1, (1 << 2) + 1, 16 >> 1 + 1)
print("bitwise order", 6 & 3 | 8, 6 & (3 | 8), 1 ^ 3 & 2, 5 | 2 ^ 7)
print("comparison vs bitwise", 1 | 2 == 3, (1 | 2) == 3, 4 & 1 == 0)
print("not with comparison", not 1 == 2, not (1 == 2), not 1 < 2, (not 1) < 2)
print("not with and/or", not 0 and 0, not (0 and 0), not 1 or 1, True or False and False, (True or False) and False)
print("and/or precedence", 1 or 0 and 0, (1 or 0) and 0, 0 and 1 or 2, 0 or 1 and 2)
print("in/not in chain", 1 in [1] == True, 1 in [1] in [[1]], 2 not in [1] != False)
print("is not chain", None is None is not False)
print("conditional expr", 1 if 0 else 2 if 0 else 3, (1 if 1 else 2) + 10, 1 + (2 if 0 else 3))
print("lambda in conditional", (lambda: 1) if False else (lambda: 2)())
print("walrus", (y := 5) * 2, y, [z := 1, z + 1])
print("await-free power with unary on rhs", 2 ** -2 ** 2, 2 ** (-2) ** 2)
print("modulo of negative literal", -7 % 3, -(7 % 3), (-7) % 3)
print("float neg pow", -2.0 ** 0.5)
print("matrix of mixes", 2 + 3 * 4 ** 2 // 5 - 1, ((2 + 3) * 4) ** 2 // 5)
print("subscript binds tighter", -[1, 2][1], [5, 6][-1] ** 2, -"ab".__len__())
print("attribute then pow", 2 .real ** 3, -(4).bit_length())
print("star expressions", [*range(3), *[x] * 2])
print("comparison chain with arithmetic", 1 + 1 == 2 < 2 + 1)
print("unary on call", -abs(-3), not bool(0), ~int("5"))
