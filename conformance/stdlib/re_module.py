"""re: match/search/fullmatch, groups and named groups, findall/finditer, sub with function and backrefs, split with captures, flags, compile, lookarounds."""
import re

print("match", re.match(r"\d+", "123abc").group(), re.match(r"\d+", "abc123"))
print("search", re.search(r"\d+", "abc123def45").group())
print("fullmatch", bool(re.fullmatch(r"[a-z]+", "abc")), re.fullmatch(r"[a-z]+", "abc1"))
m = re.search(r"(\w+)@(\w+)\.(com|org)", "contact: joe@example.com today")
print("groups", m.groups(), m.group(0), m.group(1, 3))
print("span", m.span(), m.start(2), m.end(2))
print("pos info", m.string[m.start():m.end()], m.lastindex)
d = re.match(r"(?P<year>\d{4})-(?P<month>\d\d)(?:-(?P<day>\d\d))?", "2024-07")
print("named groups", d.group("year"), d["month"], d.groupdict(), d.groupdict("none"))
print("optional group", d.group("day"), d.groups(default="?"), d.lastgroup)
print("findall plain", re.findall(r"\d+", "a1b22c333"))
print("findall one group", re.findall(r"(\w)=\d", "a=1 b=2"))
print("findall tuples", re.findall(r"(\w)=(\d)", "a=1 b=2"))
print("findall empty matches", re.findall(r"x*", "axb"))
print("finditer", [(m.group(), m.start()) for m in re.finditer(r"[A-Z]\w*", "Hi there Bob and Ann")])
print("sub backref", re.sub(r"(\w+) (\w+)", r"\2 \1", "hello world foo bar"))
print("sub named backref", re.sub(r"(?P<k>\w+)=(?P<v>\w+)", r"\g<v>:\g<k>", "a=1, b=2"))
print("sub \\g<0>", re.sub(r"\d+", r"[\g<0>]", "x1y22"))
print("sub function", re.sub(r"\d+", lambda m: str(int(m.group()) * 2), "3 apples and 10 pears"))
print("sub count", re.sub(r"a", "A", "banana", count=2))
print("subn", re.subn(r"\s+", " ", "a   b \t c\n d"))
print("sub empty matches", re.sub(r"x*", "-", "abc"))
print("split", re.split(r"[,;]\s*", "a, b;c ,d"))
print("split captures", re.split(r"([,;])", "a,b;c"))
print("split maxsplit", re.split(r"\s+", "a b c d", maxsplit=2))
print("split leading", re.split(r"\W+", "...words, here..."))
print("IGNORECASE", re.findall(r"cat", "Cat cAT cat", re.IGNORECASE))
print("MULTILINE", re.findall(r"^\w+", "one two\nthree four\nfive", re.M))
print("no MULTILINE", re.findall(r"^\w+", "one\ntwo"))
print("DOTALL", re.search(r"a.b", "a\nb"), re.search(r"a.b", "a\nb", re.S).group() == "a\nb")
pat = re.compile(r"""
    (?P<int>\d+)     # integer part
    (?:\.(?P<frac>\d+))?  # optional fraction
""", re.VERBOSE)
print("VERBOSE", [m.groupdict() for m in pat.finditer("3.14 and 42")])
print("inline flags", re.findall(r"(?i)ab", "AB ab aB"))
print("flags combine", bool(re.search(r"^b.c$", "a\nB\nC", re.I | re.M | re.S)))
word = re.compile(r"\b\w+\b")
print("compiled pattern attrs", word.pattern, word.groups)
print("compiled search pos", word.search("hello world", 5).group())
print("compiled match pos", word.match("hello world", 6).group())
print("lookahead", re.findall(r"\w+(?=!)", "hi! there bye!"))
print("neg lookahead", re.findall(r"\b\d+\b(?!px)", "10px 20 30px 40"))
print("lookbehind", re.findall(r"(?<=\$)\d+", "cost $30 or 40 or $5"))
print("neg lookbehind", re.findall(r"(?<!-)\b\d+", "5 -6 7"))
print("password check", bool(re.fullmatch(r"(?=.*\d)(?=.*[A-Z]).{6,}", "abcD3f")))
print("non-greedy", re.findall(r"<.+?>", "<a><b>"), re.findall(r"<.+>", "<a><b>"))
print("backref in pattern", re.findall(r"\b(\w)\w*\1\b", "abca xyz bob noon"))
print("alternation order", re.match(r"a|ab", "ab").group())
print("escape", re.escape("a.b*c?"), bool(re.search(re.escape("1+1"), "1+1=2")))
print("unicode word", re.findall(r"\w+", "naïve café"))
print("ASCII flag", re.findall(r"\w+", "naïve", re.ASCII))
print("bytes pattern", re.findall(rb"\d", b"a1b2"))
print("expand", re.match(r"(\w)(\w)", "ab").expand(r"\2\1"))
print("possessive/atomic", re.match(r"a++b", "aaab").group(), re.match(r"(?>a+)b", "aab").group())
try:
    re.compile(r"(unclosed")
except re.error as e:
    print("bad pattern", type(e).__name__)
print("conditional group", [bool(re.fullmatch(r"(<)?\w+(?(1)>)", s)) for s in ["<a>", "a", "<a"]])
print("fullmatch vs anchors", bool(re.match(r"a$", "a\n")), bool(re.fullmatch(r"a", "a\n")))
