"""io: StringIO and BytesIO read/write/seek/tell/getvalue/readline/iteration/truncate, TextIOWrapper over BytesIO, newline handling."""
import io

s = io.StringIO()
print("write returns", s.write("hello\n"), s.write("world"))
print("tell", s.tell())
print("getvalue", repr(s.getvalue()))
print("read at end", repr(s.read()))
s.seek(0)
print("read 3", repr(s.read(3)))
print("readline", repr(s.readline()))
print("readline last", repr(s.readline()), repr(s.readline()))
s.seek(0)
print("readlines", s.readlines())
s.seek(0)
print("iterate", [line for line in s])
s.seek(2)
s.write("LL")
print("overwrite middle", repr(s.getvalue()))
s.seek(0, io.SEEK_END)
s.write("!")
print("append at end", repr(s.getvalue()))
s.seek(3)
s.truncate()
print("truncate", repr(s.getvalue()), s.tell())
s.seek(10)
s.write("x")
print("write past end pads", repr(s.getvalue()))
init = io.StringIO("initial\ntext")
print("init position", init.tell(), repr(init.read(4)))
init.write("Z")
print("write after read", repr(init.getvalue()))
print("print to file")
out = io.StringIO()
print("a", "b", sep=",", end=";", file=out)
print(1, 2, file=out)
print("print file", repr(out.getvalue()))
out.close()
print("closed", out.closed)
try:
    out.getvalue()
except ValueError as e:
    print("use after close", type(e).__name__)
with io.StringIO("ctx") as cm:
    print("context read", cm.read())
print("context closed", cm.closed)
nl = io.StringIO("a\r\nb\rc\n", newline=None)
print("universal newlines", nl.readlines())
nl2 = io.StringIO("a\r\nb\rc\n", newline="")
print("newline empty", nl2.readlines())
print("readable/writable/seekable", s.readable(), s.writable(), s.seekable())

b = io.BytesIO()
print("bytes write", b.write(b"abc"), b.write(bytearray(b"def")), b.write(memoryview(b"gh")))
print("bytes getvalue", b.getvalue(), b.tell())
b.seek(1)
print("bytes read", b.read(2), b.read(), b.read())
b.seek(-2, io.SEEK_END)
print("seek from end", b.read())
b.seek(2)
b.seek(2, io.SEEK_CUR)
print("seek cur", b.tell(), b.read(1))
try:
    b.write("str")
except TypeError as e:
    print("bytes write str", type(e).__name__)
buf = bytearray(4)
b.seek(0)
print("readinto", b.readinto(buf), buf)
view = b.getbuffer()
view[0] = ord("Z")
print("getbuffer mutates", b.getvalue()[:3])
del view
bl = io.BytesIO(b"l1\nl2\nl3")
print("bytes lines", bl.readlines(), list(io.BytesIO(b"x\ny")))
print("read1", io.BytesIO(b"abcdef").read1(3))
raw = io.BytesIO()
w = io.TextIOWrapper(raw, encoding="utf-8", newline="\n")
w.write("café\n")
w.flush()
print("TextIOWrapper encode", raw.getvalue())
r = io.TextIOWrapper(io.BytesIO("ünï\nline2\n".encode()), encoding="utf-8")
print("TextIOWrapper decode", r.readline(), r.read().strip())
try:
    io.StringIO().seek(-1)
except ValueError as e:
    print("negative seek", type(e).__name__)
print("isinstance", isinstance(io.StringIO(), io.TextIOBase), isinstance(io.BytesIO(), io.BufferedIOBase), isinstance(io.BytesIO(), io.IOBase))
